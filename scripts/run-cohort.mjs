// Usage: node scripts/run-cohort.mjs <cohort.json> <out.json> [baseUrl=http://localhost:3000]
// Runs the exact browser pipeline (lib/pipeline.ts) headlessly against a running server and writes a demo file.
import fs from "node:fs";
import { runPipeline } from "../lib/pipeline.ts";

const [, , cohortPath, outPath, base = "http://localhost:3000"] = process.argv;
if (!cohortPath || !outPath) { console.error("usage: run-cohort.mjs <cohort.json> <out.json> [baseUrl]"); process.exit(2); }
const health = await (await fetch(base + "/api/health")).json();
if (health.mode === "live" && !health.anthropic) { console.error("Server has no ANTHROPIC_API_KEY. Configure .env.local and restart `npm run dev`."); process.exit(3); }
if (health.mode === "fixture" && !/fixture/.test(outPath)) { console.error("Refusing to write synthetic fixture output to a non-fixture file name."); process.exit(4); }
if (health.mode === "live" && /fixture/.test(outPath)) { console.error("Refusing to write live output to a fixture file name."); process.exit(4); }

const rows = JSON.parse(fs.readFileSync(cohortPath, "utf8"));
const res = await runPipeline(rows, { base, concurrency: Number(process.env.CONCURRENCY) || 4 }, { log: (m) => console.log(m) });
const failed = res.people.filter((p) => p.status === "failed");
const meta = { kind: health.mode, generated_at: new Date().toISOString(), models: health.mode === "live" ? { analyze: process.env.ANALYZE_MODEL ?? "default", date: process.env.DATE_MODEL ?? "default" } : undefined,
  note: health.mode === "fixture" ? "SYNTHETIC fixture output; no model was called." : "Generated by live model calls.", people: res.people.length, failed: failed.length, dates: res.dates.length };
fs.writeFileSync(outPath, JSON.stringify({ meta, people: res.people, dates: res.dates, shortlists: res.shortlists }, null, 1));
console.log(`\nWrote ${outPath}: ${res.people.length - failed.length}/${res.people.length} profiles, ${res.dates.length} dates` + (failed.length ? `, ${failed.length} FAILED` : ""));
process.exit(failed.length ? 1 : 0);
